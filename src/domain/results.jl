"""
Domain definitions for jobs, execution state, output artifacts, and experiment results.
"""
module Results

export JobState, Job, Artifact, Result, is_terminal, is_running

"""
    JobState

Permissible execution states in the job lifecycle.
"""
@enum JobState begin
    JOB_QUEUED
    JOB_VALIDATING
    JOB_RUNNING
    JOB_CANCELLING
    JOB_CANCELLED
    JOB_COMPLETED
    JOB_FAILED
end

function is_terminal(state::JobState)::Bool
    state in (JOB_CANCELLED, JOB_COMPLETED, JOB_FAILED)
end

function is_running(state::JobState)::Bool
    state in (JOB_VALIDATING, JOB_RUNNING, JOB_CANCELLING)
end

"""
    Job

Represents an active or historic execution task for an experiment.
"""
struct Job
    id::String
    experiment_id::String
    state::JobState
    started_at::Union{String, Nothing}
    finished_at::Union{String, Nothing}
    error_summary::Union{String, Nothing}
    termination_reason::Union{String, Nothing}
    progress::Float64   # 0.0 to 1.0, or -1.0 if not exposed by solver

    function Job(id::AbstractString, experiment_id::AbstractString, state::JobState=JOB_QUEUED;
                 started_at::Union{AbstractString, Nothing}=nothing,
                 finished_at::Union{AbstractString, Nothing}=nothing,
                 error_summary::Union{AbstractString, Nothing}=nothing,
                 termination_reason::Union{AbstractString, Nothing}=nothing,
                 progress::Real=-1.0)
        new(String(id), String(experiment_id), state,
            isnothing(started_at) ? nothing : String(started_at),
            isnothing(finished_at) ? nothing : String(finished_at),
            isnothing(error_summary) ? nothing : String(error_summary),
            isnothing(termination_reason) ? nothing : String(termination_reason),
            Float64(progress))
    end
end

"""
    Artifact

Represents an immutable disk file generated by an experiment run.
"""
struct Artifact
    name::String
    path::String
    artifact_type::String  # e.g., "chemical/x-xyz", "application/json", "text/plain"
    sha256::String
    size_bytes::Int

    function Artifact(name::AbstractString, path::AbstractString, artifact_type::AbstractString;
                      sha256::AbstractString="", size_bytes::Integer=0)
        new(String(name), String(path), String(artifact_type), String(sha256), Int(size_bytes))
    end
end

"""
    Result

Contains verified scientific output metrics and artifact manifests from an experiment.
"""
struct Result
    id::String
    experiment_id::String
    final_energy::Float64
    gradient_norm::Float64
    iterations::Int
    converged::Bool
    termination_status::String
    metrics::Dict{String, Any}
    artifacts::Vector{Artifact}
    created_at::String

    function Result(id::AbstractString, experiment_id::AbstractString;
                    final_energy::Real=NaN,
                    gradient_norm::Real=NaN,
                    iterations::Integer=0,
                    converged::Bool=false,
                    termination_status::AbstractString="unknown",
                    metrics::Dict{String, Any}=Dict{String, Any}(),
                    artifacts::Vector{Artifact}=Artifact[],
                    created_at::AbstractString="")
        new(String(id), String(experiment_id), Float64(final_energy), Float64(gradient_norm),
            Int(iterations), converged, String(termination_status), metrics, artifacts, String(created_at))
    end
end

end # module Results
