"""
Chemical structure exporters: XYZ and MDL Molfile (V2000).
"""
module Exporters

using Printf
using ..Structures: Atom, Bond, Structure
using ..Artifacts: write_atomic

export export_xyz, export_mol, export_structure

"""
    export_xyz(filepath::AbstractString, atoms::Vector{Atom}; comment::AbstractString="")
"""
function export_xyz(filepath::AbstractString, atoms::Vector{Atom}; comment::AbstractString="")
    buf = IOBuffer()
    println(buf, length(atoms))
    println(buf, isempty(comment) ? "Generated by MolecuLab" : comment)
    for a in atoms
        @printf(buf, "%-4s %14.6f %14.6f %14.6f\n", a.symbol, a.x, a.y, a.z)
    end
    write_atomic(filepath, take!(buf); artifact_type="chemical/x-xyz")
end

"""
    export_mol(filepath::AbstractString, atoms::Vector{Atom}, bonds::Vector{Bond}; title::AbstractString="")
"""
function export_mol(filepath::AbstractString, atoms::Vector{Atom}, bonds::Vector{Bond}; title::AbstractString="")
    buf = IOBuffer()
    println(buf, isempty(title) ? "MolecuLab" : title)
    println(buf, "  MolecuLab 1.0.0 3D")
    println(buf, "Generated at $(Dates.now())")

    # Counts line: I3, I3, ...
    @printf(buf, "%3d%3d  0  0  0  0  0  0  0  0999 V2000\n", length(atoms), length(bonds))

    # Atom block: 10.4f, 10.4f, 10.4f, 1X, a3
    for a in atoms
        @printf(buf, "%10.4f%10.4f%10.4f %-3s 0  0  0  0  0  0  0  0  0%3d  0  0\n",
                a.x, a.y, a.z, a.symbol, a.formal_charge)
    end

    # Bond block: 3I, 3I, 3I, ...
    for b in bonds
        order_int = round(Int, b.order)
        @printf(buf, "%3d%3d%3d  0  0  0  0\n", b.atom1, b.atom2, order_int)
    end

    println(buf, "M  END")
    write_atomic(filepath, take!(buf); artifact_type="chemical/x-mdl-molfile")
end

export_structure(filepath::AbstractString, s::Structure) =
    export_xyz(filepath, s.atoms; comment=s.name)

end # module Exporters
